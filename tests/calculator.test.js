import test from 'node:test';
import assert from 'node:assert/strict';
import { calculatorReducer, initialCalculatorState } from '../src/utils/calculator.js';
const run = (...actions) => actions.reduce(calculatorReducer, { ...initialCalculatorState });
const digit = value => ({ type: 'DIGIT', value: String(value) });
const op = value => ({ type: 'OPERATOR', value });
const equals = { type: 'EQUALS' };
test('suma', () => assert.equal(run(digit(7), op('+'), digit(5), equals).display, '12'));
test('resta', () => assert.equal(run(digit(9), op('−'), digit(4), equals).display, '5'));
test('multiplicación', () => assert.equal(run(digit(6), op('×'), digit(3), equals).display, '18'));
test('división', () => assert.equal(run(digit(8), op('÷'), digit(2), equals).display, '4'));
test('división por cero', () => assert.equal(run(digit(9), op('÷'), digit(0), equals).display, 'Error'));
test('punto decimal', () => assert.equal(run(digit(2), { type: 'DECIMAL' }, digit(5), op('+'), digit(1), equals).display, '3.5'));
test('redondeo de coma flotante', () => assert.equal(run(digit(0), { type: 'DECIMAL' }, digit(1), op('+'), digit(0), { type: 'DECIMAL' }, digit(2), equals).display, '0.3'));
test('porcentaje', () => assert.equal(run(digit(5), digit(0), { type: 'PERCENT' }).display, '0.5'));
test('cambio de signo', () => assert.equal(run(digit(7), { type: 'SIGN' }).display, '-7'));
test('retroceso', () => assert.equal(run(digit(1), digit(2), { type: 'BACKSPACE' }).display, '1'));
test('borrar', () => assert.deepEqual(run(digit(1), { type: 'CLEAR' }), initialCalculatorState));
test('operaciones encadenadas', () => assert.equal(run(digit(2), op('+'), digit(3), op('×'), digit(4), equals).display, '20'));
test('reemplazar operador pendiente', () => assert.equal(run(digit(8), op('+'), op('−'), digit(3), equals).display, '5'));
test('recuperación tras error', () => assert.equal(calculatorReducer(run(digit(8), op('÷'), digit(0), equals), digit(4)).display, '4'));
